/**
 * @param {string | undefined | null} l
 * @returns {'en' | 'nl'}
 */
export const normLocale = (l) => (String(l ?? '').toLowerCase().startsWith('nl') ? 'nl' : 'en');

/**
 * Eerste taaltag waarvan het primaire deel en of nl is.
 * @param {readonly string[]} tags
 * @returns {'en' | 'nl' | null}
 */
export function pickLocale(tags) {
  for (const tag of tags) {
    const primary = String(tag).trim().toLowerCase().split('-')[0];
    if (primary === 'en' || primary === 'nl') return primary;
  }
  return null;
}

/**
 * Taaltags uit een Accept-Language-header, gesorteerd op q (gelijke q behoudt de volgorde); q=0 en * vallen weg.
 * @param {string | null | undefined} header
 * @returns {string[]}
 */
export function parseAcceptLanguage(header) {
  if (!header) return [];
  return header
    .split(',')
    .map((part, i) => {
      const [tag, ...params] = part.trim().split(';');
      const qParam = params.map((p) => p.trim()).find((p) => p.toLowerCase().startsWith('q='));
      const q = qParam ? Number(qParam.slice(2)) : 1;
      return { tag: tag.trim(), q: Number.isFinite(q) ? q : 0, i };
    })
    .filter((x) => x.tag && x.tag !== '*' && x.q > 0)
    .sort((a, b) => b.q - a.q || a.i - b.i)
    .map((x) => x.tag);
}

/**
 * Tekst in de gevraagde taal; een ontbrekende sleutel valt terug op en en daarna op de sleutel zelf.
 * @param {string | undefined | null} locale
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 * @returns {string}
 */
export function translate(locale, key, vars = {}) {
  const s = STRINGS[normLocale(locale)][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** @type {'en' | 'nl'} */
let current = 'en';

/**
 * Taal van de client (de PWA zet die bij het opstarten uit /config.js).
 * @param {string | undefined | null} l
 * @returns {'en' | 'nl'}
 */
export const setLocale = (l) => (current = normLocale(l));

/** @returns {'en' | 'nl'} */
export const getLocale = () => current;

/**
 * @param {string} key
 * @param {Record<string, string | number>} [vars]
 * @returns {string}
 */
export const t = (key, vars) => translate(current, key, vars);

/**
 * Rangtelwoord in de taal van de app: 1st/2nd/3rd/4th of 1e/2e; -1 is "last"/"laatste".
 * @param {number} n
 * @returns {string}
 */
export function ordinal(n) {
  if (n === -1) return t('rep.last');
  if (current === 'nl') return n + 'e';
  const tens = n % 100;
  const suffix = tens >= 11 && tens <= 13 ? 'th' : ({ 1: 'st', 2: 'nd', 3: 'rd' })[n % 10] ?? 'th';
  return n + suffix;
}

/** Locale voor Intl-datums en sorteren. @returns {'en-GB' | 'nl-NL'} */
export const dateLocale = () => (current === 'nl' ? 'nl-NL' : 'en-GB');

/** Error met een vertaalsleutel; HttpError en de server vertalen hem in de taal van de installatie. */
export class KeyedError extends Error {
  /**
   * @param {string} key
   * @param {Record<string, string | number>} [vars]
   */
  constructor(key, vars = {}) {
    super(translate('en', key, vars));
    this.key = key;
    this.vars = vars;
  }
}
